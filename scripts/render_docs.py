#!/usr/bin/env python3
"""
Render a self-contained copy of the documentation, with every snippet
include replaced by the code it refers to.

The recipe pages include their code from the programs in recipes/, which
the primary pgEdge documentation site never sees; it imports only the
docs/ directory of each source. This script produces a copy of docs/ and
mkdocs.yml that needs neither recipes/ nor the Snippets extension, for
the publish workflow to push to the published branch.

The expansion uses the Snippets extension itself, configured exactly as
mkdocs.yml configures it, so the published pages contain the same code as
a local build of the site.

Usage:
    scripts/render_docs.py [--output DIRECTORY]

The output directory (build/published by default, relative to the
repository root) is replaced on each run,
and receives docs/, mkdocs.yml, and a README.md that explains its origin.

Copyright (c) 2026, pgEdge, Inc.
This code is released under the PostgreSQL License.
"""

import argparse
import os
import shutil
import sys
from pathlib import Path

import markdown
import yaml

ROOT = Path(__file__).resolve().parent.parent
SNIPPETS = "pymdownx.snippets"

README = """\
# Ellie's Postgres Cookbook (published)

This branch is generated automatically from the main branch of
[Ellie's Postgres Cookbook](https://github.com/pgEdge/ellies-postgres-cookbook)
by `scripts/render_docs.py`, with the code from each recipe inlined into the
pages. Do not edit this branch; change the main branch instead.

Generated from commit {commit}.
"""


def split_extensions(extensions):
    """Separate the Snippets configuration from the other extensions."""
    snippets_config, others = None, []
    for entry in extensions:
        name = next(iter(entry)) if isinstance(entry, dict) else entry
        if name == SNIPPETS:
            snippets_config = entry[name] if isinstance(entry, dict) else {}
        else:
            others.append(entry)
    if snippets_config is None:
        sys.exit(f"mkdocs.yml does not configure {SNIPPETS}")
    return snippets_config, others


def make_expander(config):
    """Return a function that expands the snippet includes in a page."""
    md = markdown.Markdown(extensions=[SNIPPETS],
                           extension_configs={SNIPPETS: config})
    preprocessor = md.preprocessors["snippet"]

    def expand(text):
        # The preprocessor expands includes, and turns escaped markers
        # such as ";--8<--" into literal ones; the published configuration
        # has no Snippets extension, so the literal markers stay literal.
        return "\n".join(preprocessor.run(text.split("\n")))

    return expand


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output", default="build/published",
                        help="directory to write (replaced on each run)")
    parser.add_argument("--commit", default="(unknown)",
                        help="source commit, recorded in the README")
    args = parser.parse_args()

    config_text = (ROOT / "mkdocs.yml").read_text()
    config = yaml.safe_load(config_text)
    docs_dir = ROOT / config.get("docs_dir", "docs")

    snippets_config, other_extensions = split_extensions(
        config.get("markdown_extensions", []))

    # Snippet paths are relative to base_path, which is relative to the
    # working directory, as in a normal build from the repository root.
    expand = make_expander(snippets_config)

    output = (ROOT / args.output).resolve()
    if output in (ROOT, docs_dir) or output in ROOT.parents:
        sys.exit(f"Refusing to overwrite {output}")
    if output.exists():
        shutil.rmtree(output)
    shutil.copytree(docs_dir, output / "docs")

    expanded = 0
    for page in sorted((output / "docs").rglob("*.md")):
        source = page.read_text()
        if "--8<--" not in source:
            continue
        page.write_text(expand(source))
        expanded += 1

    # The published configuration is the same, less the Snippets extension.
    config["markdown_extensions"] = other_extensions
    (output / "mkdocs.yml").write_text(
        "# Generated by scripts/render_docs.py; do not edit.\n"
        + yaml.safe_dump(config, sort_keys=False, allow_unicode=True))
    (output / "README.md").write_text(README.format(commit=args.commit))

    print(f"Rendered {expanded} page(s) with snippets into {output}")


if __name__ == "__main__":
    # Resolve snippet paths, and the output directory, from the repository
    # root, wherever the script is run from.
    os.chdir(ROOT)
    main()
